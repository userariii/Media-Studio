@Composable
fun MultimediaStudioTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    appThemeColor: AppThemeColor = AppThemeColor.MONOCHROME,
    content: @Composable () -> Unit,
) {
    val colorScheme = when (appThemeColor) {
        AppThemeColor.OCEAN -> if (darkTheme) OceanDarkColorScheme else OceanLightColorScheme
        AppThemeColor.EMERALD -> if (darkTheme) EmeraldDarkColorScheme else EmeraldLightColorScheme
        AppThemeColor.AMBER -> if (darkTheme) AmberDarkColorScheme else AmberLightColorScheme
        AppThemeColor.CRIMSON -> if (darkTheme) CrimsonDarkColorScheme else CrimsonLightColorScheme
        AppThemeColor.MONOCHROME -> if (darkTheme) MonochromeDarkColorScheme else MonochromeLightColorScheme
        AppThemeColor.DEFAULT -> if (darkTheme) DarkColorScheme else LightColorScheme
    }

    val view = LocalView.current
    if (!view.isInEditMode) {
        SideEffect {
            val window = (view.context as? Activity)?.window
            if (window != null) {
                val insetsController = WindowCompat.getInsetsController(window, view)
                insetsController.isAppearanceLightStatusBars = !darkTheme
                insetsController.isAppearanceLightNavigationBars = !darkTheme
            }
        }
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content,
    )
}
